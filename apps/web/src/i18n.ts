function fill(template: string, params: Record<string, unknown>): string {
  return template.replace(/\{(\w+)\}/g, (_, key: string) => (params[key] === undefined ? `{${key}}` : String(params[key])))
}

export interface I18n {
  lang: Lang
  t(key: Key, params?: Record<string, unknown>): string
  message(message: Message): string
  setLang(lang: Lang): void
}

export function makeI18n(lang: Lang, setLang: (lang: Lang) => void): I18n {
  return {
    lang,
    setLang,
    t: (key, params = {}) => fill(CATALOGS[lang][key], params),
    message: (m) => {
      const template = CODES[lang][m.code]
      const params = (m.params ?? {}) as Record<string, unknown>
      return template ? fill(template, params) : `${m.code} ${Object.keys(params).length ? JSON.stringify(params) : ''}`.trim()
    },
  }
}

export const I18nContext = createContext<I18n>(makeI18n('zh', () => {}))
export const useI18n = () => useContext(I18nContext)
