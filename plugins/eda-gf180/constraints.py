"""Timing constraints from the chip spec (requirements FR-SGN-02a/02b).

The SDC is generated from the chip spec's interface timing, so every input and
output delay has a documented source. It contains no timing exceptions: an
exception enters only through the registry, which a human approves.
"""

from __future__ import annotations

import re

# Electrical environment of the board when the chip spec does not state it.
OUTPUT_LOAD_PF = 5.0
INPUT_TRANSITION_NS = 2.0
CLOCK_UNCERTAINTY_NS = 0.5

EXCEPTION_COMMANDS = (
    "set_false_path",
    "set_multicycle_path",
    "set_case_analysis",
    "set_disable_timing",
    "set_max_delay",
    "set_min_delay",
)


def sdc_from_spec(chip: dict) -> str:
    timing = chip["timing"]
    clock = timing["clock"]
    board = timing.get("board") or {}
    load = board.get("outputLoadPf", OUTPUT_LOAD_PF)
    transition = board.get("inputTransitionNs", INPUT_TRANSITION_NS)
    lines = [
        "# Generated by eda-gf180 from the chip spec's interface timing; do not edit.",
        f"create_clock -name clk -period {clock['periodNs']} [get_ports {clock['port']}]",
        f"set_clock_uncertainty {CLOCK_UNCERTAINTY_NS} [get_clocks clk]",
        "set_propagated_clock [get_clocks clk]",
    ]
    for port, d in sorted(timing["inputs"].items()):
        lines += [
            f"set_input_delay -clock clk -max {d['maxNs']} [get_ports {port}]",
            f"set_input_delay -clock clk -min {d['minNs']} [get_ports {port}]",
            f"set_input_transition {transition} [get_ports {port}]",
        ]
    for port, d in sorted(timing["outputs"].items()):
        lines += [
            f"set_output_delay -clock clk -max {d['maxNs']} [get_ports {port}]",
            f"set_output_delay -clock clk -min {d['minNs']} [get_ports {port}]",
            f"set_load {load} [get_ports {port}]",
        ]
    return "\n".join(lines) + "\n"


def sdc_commands(sdc: str) -> list[str]:
    """SDC commands with line continuations joined and comments removed."""
    text = re.sub(r"\\\n", " ", sdc)
    return [line.strip() for line in text.splitlines() if line.strip() and not line.strip().startswith("#")]


def exceptions(sdc: str) -> list[str]:
    return [c for c in sdc_commands(sdc) if c.split()[0] in EXCEPTION_COMMANDS]


def delayed_ports(sdc: str) -> dict[str, set[str]]:
    """Ports whose input or output delay constrains both setup and hold: a `-max` and a `-min`
    delay, or one delay without either flag (which sets both). A port with only one bound is
    not constrained (FR-SGN-02a)."""
    bounds: dict[str, dict[str, set[str]]] = {"input": {}, "output": {}}
    for c in sdc_commands(sdc):
        m = re.match(r"set_(input|output)_delay\b(.*)\[get_ports\s+\{?([^\]}]+)\}?\]", c)
        if not m:
            continue
        flags = m.group(2).split()
        which = (
            {"max", "min"}
            if "-max" not in flags and "-min" not in flags
            else {f[1:] for f in flags if f in ("-max", "-min")}
        )
        for port in m.group(3).split():
            bounds[m.group(1)].setdefault(port, set()).update(which)
    return {kind: {p for p, b in ports.items() if b >= {"max", "min"}} for kind, ports in bounds.items()}


def clocks(sdc: str) -> list[str]:
    return [c for c in sdc_commands(sdc) if c.startswith(("create_clock", "create_generated_clock"))]
