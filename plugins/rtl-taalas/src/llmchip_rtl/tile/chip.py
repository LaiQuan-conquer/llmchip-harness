"""The Q-full chip of taalas-tile/1: embedding, layer chain, tail (final norm + lm_head), argmax
and the token loop (drafts/Qwen05B_Taalas_Refactor_Plan_zh.md §12.1 B3).

The host side is parallel here (start, token, length in; busy, done, next_token out); `tile_host`
turns SPI frames into exactly these signals and is tested on its own. `narrow` to the residual and
logit widths follows GraphL2's own arithmetic.
"""

from __future__ import annotations

import hashlib
import math
from pathlib import Path

import numpy as np

from . import rom
from .chain import _split, _pack

EPS = 1e-6


def _wfile(path: Path, values: np.ndarray, bits: int = 16) -> None:
    mask = (1 << bits) - 1
    path.write_text("\n".join(f"{int(v) & mask:0{bits // 4}x}" for v in np.asarray(values).ravel()) + "\n")


def generate(out: Path, spec: dict, arrays: dict[str, np.ndarray], macs: int) -> dict:
    h = spec["hyper"]
    bits = int(spec["weights"]["storageBits"])
    res = int(spec["activations"]["bits"]["x"])
    frac = spec["activations"]["frac"]
    context = int(spec["context"]["maxTokens"])
    log2context = (context - 1).bit_length()
    vocab = int(h["vocab"])
    hidden, inter = int(h["hidden"]), int(h["intermediate"])
    group = int(spec["weights"]["groupSize"])
    cpg = group // macs
    exp = int(spec["weights"]["exponents"]["embed"])
    logits_frac = int(spec["logits"]["frac"])

    rtl = out / "rtl"
    q = np.asarray(arrays["embed.q"]).astype(np.int64)
    words = rom.to_words(q, macs, bits)
    _split(out, "embed", words, macs, bits)
    _wfile(out / "embed_m.hex", arrays["embed.m"], 16)
    b = arrays.get("embed.b")
    b = np.zeros(vocab, dtype=np.int64) if b is None else np.asarray(b).astype(np.int64)
    _wfile(out / "embed_b.hex", b, 32 if res > 16 else 16)
    (out / "final_w.hex").write_text(_pack(arrays["final_norm.w"], 16) + "\n")

    eps_attn = round(EPS * 2.0 ** (2 * int(frac["x"])))
    chunks = hidden // macs
    l2ch = (chunks - 1).bit_length()
    l2rows = (vocab - 1).bit_length()
    l2addr = (vocab * chunks - 1).bit_length()
    l2macs = (macs - 1).bit_length()
    l2cpg = (cpg - 1).bit_length()
    ngroups = hidden // group

    text = f"""// The Q-full chip: embedding -> layer chain -> final norm -> lm_head -> argmax, repeated for
// `length` tokens. Generated by llmchip_rtl.tile.chip. The host side is parallel signals.
`default_nettype none

module tile_chip #(
  parameter integer HIDDEN = {hidden},
  parameter integer RES = {res},
  parameter integer LAYERS = {int(h['layers'])}
) (
  input  wire                         clk,
  input  wire                         rst_n,
  input  wire                         start,
  input  wire [23:0]                  token,
  input  wire [15:0]                  position,
  input  wire [15:0]                  length,
  output wire                         busy,
  output reg                          done,
  output reg  [23:0]                  next_token,
  input  wire [15:0]                  obs_addr,
  output reg  [15:0]                  obs_word,
  output wire [LAYERS*16-1:0]         dbg_sig,
  output wire [63:0]                  dbg_sum,
  output wire                         dbg_valid
);

  localparam integer VOCAB = {vocab};
  localparam integer CONTEXT = {context};

  localparam [3:0] S_IDLE = 4'd0, S_EMB0 = 4'd1, S_EMB1 = 4'd2, S_CH0 = 4'd3, S_CH1 = 4'd4,
                   S_NM0 = 4'd5, S_NM1 = 4'd6, S_LMW = 4'd7, S_LMS = 4'd8, S_LM1 = 4'd9,
                   S_LM = 4'd10, S_EMIT = 4'd11, S_DONE = 4'd12;

  reg [3:0] state;
  reg [23:0] tok;
  reg [15:0] pos;
  reg [15:0] left;
  reg signed [31:0] best;
  reg [23:0] best_idx;
  reg [31:0] wcount;

  wire embed_start;
  wire signed [HIDDEN*RES-1:0] embed_x;
  wire embed_done;
  wire chain_start;
  wire signed [HIDDEN*RES-1:0] chain_x2;
  wire chain_done;
  wire chain_busy;
  wire norm_start;
  wire signed [HIDDEN*16-1:0] norm_y;
  wire norm_done;
  wire lm_start;
  wire signed [31:0] lm_y;
  wire lm_yv;
  wire lm_done;
  wire [{l2rows - 1}:0] lm_yi;
  wire [63:0] chain_sum;
  wire chain_valid;
  wire [31:0] lm_raw;
  wire lm_rawv;
  wire [63:0] lm_total;
  wire lm_totalv;
  wire signed [HIDDEN*RES-1:0] x_fin;
  wire signed [HIDDEN*16-1:0] h_norm;
  reg [HIDDEN*16-1:0] final_w_mem [0:0];
  wire signed [HIDDEN*16-1:0] final_w = final_w_mem[0];
  wire wr_en;
  wire [{l2ch - 1}:0] wr_chunk;
  wire [{l2macs - 1}:0] wr_lane;
  wire signed [15:0] wr_data;

  tile_embed #(
    .HIDDEN(HIDDEN), .VOCAB(VOCAB), .GROUP({group}), .MACS({macs}), .BITS({bits}), .CPG({cpg}),
    .RES(RES), .EXP({exp}), .FRAC_X({int(frac['x'])}),
    .INIT0("embed_bank0.hex"), .INIT1("embed_bank1.hex"),
    .INIT2("embed_bank2.hex"), .INIT3("embed_bank3.hex"), .INIT_M("embed_m.hex")
  ) embed (
    .clk(clk), .rst_n(rst_n), .start(embed_start), .token(tok), .x(embed_x), .done(embed_done)
  );

  tile_chain chain (
    .clk(clk), .rst_n(rst_n), .start(chain_start), .position(pos),
    .x(x_fin), .x2(chain_x2), .done(chain_done), .busy(chain_busy),
    .obs_sig(dbg_sig), .obs_sum(chain_sum), .obs_valid(chain_valid)
  );

  tile_rmsnorm #(
    .DIM(HIDDEN), .WIDTH(RES), .LOG2DIM($clog2(HIDDEN)), .FN({int(spec['normWeights']['frac'])}), .FO({int(frac['xn'])}),
    .EPS_Q({eps_attn}), .INIT("rsqrt.hex")
  ) final_norm (
    .clk(clk), .rst_n(rst_n), .start(norm_start), .x(x_fin), .weight(final_w),
    .y(norm_y), .done(norm_done)
  );

  initial $readmemh("final_w.hex", final_w_mem);

  tile_linear #(
    .MACS({macs}), .BITS({bits}), .ACC(32), .GROUPS(8), .ROWS(VOCAB), .CHUNKS({chunks}),
    .LOG2CHUNKS({l2ch}), .LOG2ROWS({l2rows}), .LOG2ADDR({l2addr}), .LOG2MACS({l2macs}),
    .LOG2CPG({l2cpg}), .NGROUPS({ngroups}), .FRAC_IN({int(frac['xn'])}), .FRAC_OUT({logits_frac}),
    .EXP({exp}), .BIAS_BITS(32), .Y_BITS(32),
    .INIT0("embed_bank0.hex"), .INIT1("embed_bank1.hex"),
    .INIT2("embed_bank2.hex"), .INIT3("embed_bank3.hex"), .INIT_M("embed_m.hex"), .INIT_B("embed_b.hex")
  ) lm_head (
    .clk(clk), .rst_n(rst_n), .start(lm_start),
    .x_wr_en(wr_en), .x_wr_chunk(wr_chunk), .x_wr_lane(wr_lane), .x_wr_data(wr_data),
    .y(lm_y), .y_valid(lm_yv), .y_index(lm_yi), .done(lm_done),
    .raw_y(lm_raw), .raw_y_valid(lm_rawv), .total_y(lm_total), .total_valid(lm_totalv)
  );

  assign embed_start = (state == S_EMB0);
  assign chain_start = (state == S_CH0);
  assign norm_start = (state == S_NM0);
  assign lm_start = (state == S_LMS);
  assign busy = (state != S_IDLE);
  assign dbg_sum = chain_sum ^ lm_total ^ {{32'd0, lm_raw}};
  assign dbg_valid = chain_valid | lm_rawv | lm_totalv;

  assign wr_en = (state == S_LMW);
  assign wr_chunk = wcount[{l2macs} +: {l2ch}];
  assign wr_lane = wcount[{l2macs - 1}:0];
  assign wr_data = h_norm[wcount*16 +: 16];
  assign h_norm = norm_y;
  assign x_fin = ((state == S_EMB1) || (state == S_CH0)) ? embed_x : chain_x2;

  always @(posedge clk or negedge rst_n) begin
    if (!rst_n) begin
      state <= S_IDLE;
      tok <= 24'd0;
      pos <= 16'd0;
      left <= 16'd0;
      best <= 32'sh80000000;
      best_idx <= 24'd0;
      wcount <= 32'd0;
      done <= 1'b0;
      next_token <= 24'd0;
    end else begin
      done <= 1'b0;
      case (state)
        S_IDLE: begin
          if (start) begin
            tok <= token;
            pos <= position;
            left <= length;
            best <= 32'sh80000000;
            state <= S_EMB0;
          end
        end
        S_EMB0: state <= S_EMB1;
        S_EMB1: begin
          if (embed_done) begin
            state <= S_CH0;
          end
        end
        S_CH0: state <= S_CH1;
        S_CH1: begin
          if (chain_done) begin
            state <= S_NM0;
          end
        end
        S_NM0: state <= S_NM1;
        S_NM1: begin
          if (norm_done) begin
            wcount <= 32'd0;
            state <= S_LMW;
          end
        end
        S_LMW: begin
          if (wcount == HIDDEN - 1) begin
            state <= S_LMS;
          end else begin
            wcount <= wcount + 32'd1;
          end
        end
        S_LMS: begin
          best <= 32'sh80000000;
          best_idx <= 24'd0;
          state <= S_LM1;
        end
        S_LM1: state <= S_LM;
        S_LM: begin
          if (lm_yv && ($signed(lm_y) > best)) begin
            best <= lm_y;
            best_idx <= lm_yi;
          end
          if (lm_done) begin
            state <= S_EMIT;
          end
        end
        S_EMIT: begin
          next_token <= best_idx;
          if (left > 16'd1) begin
            tok <= best_idx;
            pos <= pos + 16'd1;
            left <= left - 16'd1;
            state <= S_EMB0;
          end else begin
            state <= S_DONE;
          end
        end
        S_DONE: begin
          done <= 1'b1;
          state <= S_IDLE;
        end
        default: state <= S_IDLE;
      endcase
    end
  end

  always @(*) begin
    obs_word = 16'd0;
    if (obs_addr < HIDDEN) begin
      obs_word = chain_x2[obs_addr*RES +: RES];
    end else if (obs_addr == HIDDEN) begin
      obs_word = next_token[15:0];
    end else if (obs_addr == HIDDEN + 1) begin
      obs_word = pos;
    end
  end

endmodule
"""
    (rtl / "tile_chip.v").write_text(text)
    return {"file": "rtl/tile_chip.v", "sha256": hashlib.sha256(text.encode()).hexdigest(), "layers": int(h["layers"])}
