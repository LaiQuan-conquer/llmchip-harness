"""Writes a generated design as a self-contained RTL bundle (a deterministic tar archive)."""

from __future__ import annotations

import io
import json
import tarfile
from importlib import resources
from pathlib import Path

import numpy as np

from .compiler import MAPPING_RULE, Compiled
from .isa import OPS, WORD_BITS, decode

RTL_FILES = (
    "llmchip_core.v",
    "llmchip_functions.vh",
    "llmchip_spimem.v",
    "llmchip_host.v",
    "llmchip_chip.v",
    "llmchip_alu.v",
    "tb_top.v",
    "gl_tb.v",
    "spi_sram_model.v",
    "tb.cpp",
)
FIELDS_USED = 14  # instruction fields the engine reads (F0..F13)


def hex_words(words: list[int], bits: int) -> str:
    digits = -(-bits // 4)
    mask = (1 << bits) - 1
    return "".join(f"{w & mask:0{digits}x}\n" for w in words)


def pack_lanes(rows: np.ndarray, bits: int) -> list[int]:
    mask = (1 << bits) - 1
    out = []
    for row in rows.tolist():
        word = 0
        for lane, value in enumerate(row):
            word |= (int(value) & mask) << (lane * bits)
        out.append(word)
    return out


def case_rom(name: str, addr_bits: int, data_bits: int, words: list[int], signed: bool = False) -> str:
    """A combinational ROM as a case statement (the standard-cell ROM of the prerun)."""
    sign = "signed " if signed else ""
    digits = -(-data_bits // 4)
    mask = (1 << data_bits) - 1
    lines = [
        f"module {name} (input wire [{addr_bits - 1}:0] addr, output reg {sign}[{data_bits - 1}:0] data);",
        "  always @* begin",
        "    case (addr)",
    ]
    lines += [f"      {a}: data = {data_bits}'h{w & mask:0{digits}x};" for a, w in enumerate(words) if w & mask]
    lines += [f"      default: data = {data_bits}'h0;", "    endcase", "  end", "endmodule", ""]
    return "\n".join(lines)


def prog_rom(c: Compiled) -> str:
    """The program ROM: opcode and fields per instruction. Simulation may replace the
    program with +prog=FILE (instruction words in the format of isa.py)."""
    pcw = c.widths["PCW"]
    outs = ", ".join(f"output reg signed [31:0] f{k}" for k in range(FIELDS_USED))
    lines = [
        f"module llmchip_prog (input wire [{pcw - 1}:0] pc, output reg [7:0] op, {outs});",
        "`ifndef SYNTHESIS",
        f"  reg [{WORD_BITS - 1}:0] override [0:{(1 << pcw) - 1}];",
        "  reg [8*256-1:0] file;",
        "  reg use_override;",
        "  initial begin",
        '    use_override = $value$plusargs("prog=%s", file);',
        "    if (use_override) $readmemh(file, override);",
        "  end",
        "`endif",
        "  always @* begin",
        "    op = 8'd0;",
        *[f"    f{k} = 32'sd0;" for k in range(FIELDS_USED)],
        "    case (pc)",
    ]
    for pc, word in enumerate(c.program):
        op, fields = decode(word)
        body = [f"op = 8'd{OPS[op]};"] + [
            f"f{k} = {'-' if v < 0 else ''}32'sd{abs(v)};" for k, v in enumerate(fields[:FIELDS_USED]) if v
        ]
        if any(fields[FIELDS_USED:]):
            raise ValueError(f"instruction {pc} uses fields beyond F{FIELDS_USED - 1}")
        lines.append(f"      {pc}: begin {' '.join(body)} end")
    lines += [
        "      default: ;",
        "    endcase",
        "`ifndef SYNTHESIS",
        "    if (use_override) begin",
        "      op = override[pc][7:0];",
        *[f"      f{k} = override[pc][{8 + 32 * k + 31}:{8 + 32 * k}];" for k in range(FIELDS_USED)],
        "    end",
        "`endif",
        "  end",
        "endmodule",
        "",
    ]
    return "\n".join(lines)


def bundle_files(c: Compiled, source: dict | None = None) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    pkg = resources.files("llmchip_rtl") / "rtl"
    for name in RTL_FILES:
        files[f"rtl/{name}"] = (pkg / name).read_bytes()
    files["isa.py"] = (resources.files("llmchip_rtl") / "isa.py").read_bytes()
    w = c.widths
    params = {
        "LANES": c.lanes,
        "LANES_LOG2": c.lanes.bit_length() - 1,
        "WBITS": c.wbits,
        "CTX": c.context,
        "VOCAB": c.cfg["vocab_size"],
        **w,
        "NPROG": len(c.program),
        "NDMEM": c.dmem_words,
    }
    flags = ("RSH_POSITIVE", "SILU_FRAC_GE4", "ROUND_HALF_EVEN", "ROUND_TRUNCATE", "OVERFLOW_WRAP", "ACC_NARROW")
    files["rtl/llmchip_params.vh"] = (
        "// Generated by rtl-taalas; do not edit.\n"
        + "".join(f"`define {k} {v}\n" for k, v in params.items() if k not in flags)
        + "".join(f"`define {k}\n" for k in flags if params[k])
    ).encode()
    roms = [
        "// Generated by rtl-taalas from the numeric spec and weights; do not edit.",
        "// Mapping rule: " + MAPPING_RULE,
        "`timescale 1ns/1ps",
        "/* verilator lint_off DECLFILENAME */",
        prog_rom(c),
        case_rom("llmchip_wrom", w["WAW"], c.lanes * c.wbits, pack_lanes(c.wrom, c.wbits)),
        case_rom("llmchip_srom", w["SAW"], c.lanes * 15, pack_lanes(c.srom, 15)),
        case_rom("llmchip_crom", w["CAW"], w["CW"], [int(v) for v in c.crom], signed=True),
        "/* verilator lint_on DECLFILENAME */",
    ]
    files["rtl/llmchip_roms.v"] = ("\n".join(roms) + "\n").encode()
    files["rtl/trace.map"] = "".join(
        f"{t['op']} {t['point']} {t['layer']} {t['n']} {t['addr']} {int(t['debug'])}\n" for t in c.trace_map
    ).encode()
    cfg = c.cfg
    design = {
        "format": "llmchip-rtl-bundle/2",
        "top": "llmchip_chip",
        "source": source or {},
        "params": params,
        "model": {k: cfg[k] for k in ("dim", "hidden_dim", "n_layers", "n_heads", "n_kv_heads", "vocab_size")},
        "program": c.descriptions,
        "debugMap": c.debug_map,
        "traceMap": c.trace_map,
        "layout": c.layout,
        "sources": [
            f"rtl/{n}"
            for n in ("llmchip_core.v", "llmchip_spimem.v", "llmchip_host.v", "llmchip_chip.v", "llmchip_roms.v")
        ],
        "includes": ["rtl/llmchip_params.vh", "rtl/llmchip_functions.vh"],
        "interfaces": {
            "host": "SPI slave mode 0, SCK <= clk/8: 0x10 START token[15:0] pos[15:0] mode[7:0]; "
            "0x20 STATUS -> busy error done 13'b0 token[15:0]",
            "memory": "SPI master mode 0, SCK = clk/2, 23LC1024-style SRAM, "
            "32-bit words MSB first at byte address 4*addr",
        },
    }
    files["design.json"] = json.dumps(design, indent=2).encode()
    np_buf = io.BytesIO()
    np.savez(np_buf, wrom=c.wrom, srom=c.srom, crom=c.crom, program=np.array([str(w) for w in c.program]))
    files["isa-image.npz"] = np_buf.getvalue()
    return files


def write_tar(files: dict[str, bytes], path: str | Path) -> None:
    """Deterministic: sorted names, fixed mtime, owner and mode."""
    with tarfile.open(path, "w", format=tarfile.USTAR_FORMAT) as tar:
        for name in sorted(files):
            info = tarfile.TarInfo(f"bundle/{name}")
            info.size = len(files[name])
            info.mtime = 0
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            tar.addfile(info, io.BytesIO(files[name]))
