"""Writes a generated design as a self-contained RTL bundle (a deterministic tar archive)."""

from __future__ import annotations

import io
import json
import tarfile
from importlib import resources
from pathlib import Path

import numpy as np

from .compiler import Compiled
from .isa import WORD_BITS

RTL_FILES = ("llmchip_core.v", "llmchip_functions.vh", "llmchip_alu.v", "tb.cpp")


def hex_words(words: list[int], bits: int) -> str:
    digits = -(-bits // 4)
    mask = (1 << bits) - 1
    return "".join(f"{w & mask:0{digits}x}\n" for w in words)


def pack_lanes(rows: np.ndarray, bits: int) -> list[int]:
    mask = (1 << bits) - 1
    out = []
    for row in rows.tolist():
        word = 0
        for lane, value in enumerate(row):
            word |= (int(value) & mask) << (lane * bits)
        out.append(word)
    return out


def bundle_files(c: Compiled, source: dict | None = None) -> dict[str, bytes]:
    files: dict[str, bytes] = {}
    pkg = resources.files("llmchip_rtl") / "rtl"
    for name in RTL_FILES:
        files[f"rtl/{name}"] = (pkg / name).read_bytes()
    files["isa.py"] = (resources.files("llmchip_rtl") / "isa.py").read_bytes()
    params = {
        "LANES": c.lanes,
        "LANES_LOG2": c.lanes.bit_length() - 1,
        "WBITS": c.wbits,
        "NWROM": len(c.wrom),
        "NSROM": len(c.srom),
        "NCROM": len(c.crom),
        "NPROG": max(len(c.program), len(c.debug_program)),
        "NDMEM": c.dmem_words,
        "CTX": c.context,
        "VOCAB": c.cfg["vocab_size"],
    }
    files["rtl/llmchip_params.vh"] = (
        "// Generated by rtl-taalas; do not edit.\n" + "".join(f"`define {k} {v}\n" for k, v in params.items())
    ).encode()
    files["rtl/wrom.hex"] = hex_words(pack_lanes(c.wrom, c.wbits), c.lanes * c.wbits).encode()
    files["rtl/srom.hex"] = hex_words(pack_lanes(c.srom, 15), c.lanes * 15).encode()
    files["rtl/crom.hex"] = hex_words([int(v) for v in c.crom], 32).encode()
    files["rtl/prog.hex"] = hex_words(c.program, WORD_BITS).encode()
    files["rtl/prog_debug.hex"] = hex_words(c.debug_program, WORD_BITS).encode()
    cfg = c.cfg
    design = {
        "format": "llmchip-rtl-bundle/1",
        "top": "llmchip_core",
        "source": source or {},
        "params": params,
        "model": {k: cfg[k] for k in ("dim", "hidden_dim", "n_layers", "n_heads", "n_kv_heads", "vocab_size")},
        "program": c.descriptions,
        "debugMap": c.debug_map,
        "layout": c.layout,
        "roms": {"wrom": "rtl/wrom.hex", "srom": "rtl/srom.hex", "crom": "rtl/crom.hex"},
    }
    files["design.json"] = json.dumps(design, indent=2).encode()
    np_buf = io.BytesIO()
    np.savez(
        np_buf,
        wrom=c.wrom,
        srom=c.srom,
        crom=c.crom,
        program=np.array([str(w) for w in c.program]),
        debug=np.array([str(w) for w in c.debug_program]),
    )
    files["isa-image.npz"] = np_buf.getvalue()
    return files


def write_tar(files: dict[str, bytes], path: str | Path) -> None:
    """Deterministic: sorted names, fixed mtime, owner and mode."""
    with tarfile.open(path, "w", format=tarfile.USTAR_FORMAT) as tar:
        for name in sorted(files):
            info = tarfile.TarInfo(f"bundle/{name}")
            info.size = len(files[name])
            info.mtime = 0
            info.mode = 0o644
            info.uid = info.gid = 0
            info.uname = info.gname = ""
            tar.addfile(info, io.BytesIO(files[name]))
